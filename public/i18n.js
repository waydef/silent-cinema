const LANG = (() => {
  const store = (v) => { try { localStorage.setItem('wp.lang', v); } catch { /* private mode */ } };
  const asked = new URLSearchParams(location.search).get('lang');
  if (asked && I18N[asked]) { store(asked); return asked; }
  try { const saved = localStorage.getItem('wp.lang'); if (I18N[saved]) return saved; } catch { /* private mode */ }
  for (const l of navigator.languages || [navigator.language || '']) {
    const base = String(l).slice(0, 2).toLowerCase();
    if (I18N[base]) return base;
  }
  return 'en';
})();

function tr(key, vars = {}) {
  const v = I18N[LANG][key] ?? I18N.en[key];
  if (v === undefined) return key;
  if (typeof v === 'function') return v(vars);
  return v.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

// server errors arrive as codes; anything else (an ffmpeg message) is shown as it came
const errText = (code, vars) => (I18N.en[`err.${code}`] ? tr(`err.${code}`, vars) : String(code || ''));

// static markup: data-t sets the text, data-t-ph / data-t-aria / data-t-title the attributes
function translate(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll('[data-t]')) el.textContent = tr(el.dataset.t);
  for (const el of root.querySelectorAll('[data-t-ph]')) el.placeholder = tr(el.dataset.tPh);
  for (const el of root.querySelectorAll('[data-t-aria]')) el.setAttribute('aria-label', tr(el.dataset.tAria));
  for (const el of root.querySelectorAll('[data-t-title]')) el.title = tr(el.dataset.tTitle);
}
translate();
